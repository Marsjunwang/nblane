/** Deterministic PRNG (mulberry32) — the starmap layout must be stable
 * across renders for the same data, so every jitter draws from seeded
 * streams instead of Math.random. Ported from the playground rng.js. */
export function mulberry32(seed: number): () => number {
  let a = seed >>> 0;
  return () => {
    a |= 0;
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
